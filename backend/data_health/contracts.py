"""Contracts: what a source must keep being (WS6 M4, plan §3.6).

Three layers, all checked on every run next to freshness:

1. **Fields we read.** For each Socrata source, the columns its owning module mentions
   (``fields_read.json``, generated by ``--scan``). A column the publisher renames or drops makes the
   module read ``None`` silently; the contract turns that into an ``error`` on the next run. This is the
   check that would have flagged ``t68z-cikk`` (the demographics module read poverty, rent and tenure
   columns the dataset never had).
2. **Value sets.** A field whose meaning we derive facts from may only hold known values: layer 1's
   ``ZONE_CLASS`` starts with a known district family, layer 6's ``LANDMARK`` is Y or N, Address Points'
   ``st_predir`` is a compass word.
3. **Row-count bands.** Fixed-size sets (50 wards, 77 community areas) and the layer feature counts the
   registry already carries.

    python -m backend.data_health.contracts --scan            # compare the file with the code and the live schemas
    python -m backend.data_health.contracts --scan --write    # regenerate fields_read.json

Pure functions plus a scanner. The scanner reads only the committed modules and the public ``/api/views``
schemas; no model calls.
"""

from __future__ import annotations

import argparse
import ast
import asyncio
import json
import re
import sys
from pathlib import Path

from backend.data_health.evaluate import Finding
from backend.data_health.registry import FIELDS_READ_PATH, PORTAL_HOSTS, SOURCES, SourceSpec, ValueSpec

REPO = Path(__file__).resolve().parents[2]


def module_words(path: Path) -> set[str]:
    """Every lowercase identifier-like word inside a string literal of a module (a column read as
    ``row.get("pin")``, selected in ``"$select": "pin,lat"`` or compared in ``$where``)."""
    tree = ast.parse(path.read_text())
    words: set[str] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Constant) and isinstance(node.value, str):
            words.update(re.findall(r"[a-z_][a-z0-9_]{2,}", node.value))
    return words


# Modules that read a source's rows although the source's own module only fetches them: the property
# orchestrator builds the Profile's assessment, characteristics, sales and appeals facts from the raw rows.
EXTRA_READERS: dict[str, tuple[str, ...]] = {
    sid: ("backend/retrieval/property/__init__.py",)
    for sid in ("cook.assessor.values", "cook.assessor.characteristics", "cook.assessor.sales", "cook.assessor.appeals",
                "cook.bor.appeals", "cook.assessor.permits")
}


def reader_modules(spec: SourceSpec) -> list[Path]:
    """Every committed Python module that reads this source's columns: its owners plus any extra readers."""
    paths = [REPO / m for m in (*spec.owner_modules, *EXTRA_READERS.get(spec.id, ()))]
    return [p for p in paths if p.suffix == ".py" and p.exists()]


def fields_read(spec: SourceSpec, columns: set[str]) -> list[str]:
    """The columns of ``spec``'s dataset that its reader modules mention, in dataset order."""
    words: set[str] = set()
    for path in reader_modules(spec):
        words |= module_words(path)
    return sorted(c for c in columns if c in words)


def value_findings(spec: SourceSpec, observed: dict[str, tuple[str, ...]]) -> list[Finding]:
    """Findings for values outside the contract. ``observed`` maps a field to its distinct values."""
    out: list[Finding] = []
    c = spec.contract
    for v in (c.values if c else ()):
        seen = observed.get(v.field)
        if seen is None:
            continue
        bad = sorted({x for x in seen if x.strip() and not _allowed(v, x.strip())})
        if bad:
            shown = ", ".join(repr(b) for b in bad[:5]) + (f" and {len(bad) - 5} more" if len(bad) > 5 else "")
            out.append(Finding("alarm", f"{v.field}: unexpected value(s) {shown}"))
        if not seen:
            out.append(Finding("alarm", f"{v.field}: no values came back"))
    return out


def _allowed(v: ValueSpec, value: str) -> bool:
    if v.allowed:
        return value in v.allowed
    if v.prefixes:
        return any(value.upper().startswith(p) for p in v.prefixes)
    return True


# --- the scanner ---------------------------------------------------------------------------------

async def _live_columns(spec: SourceSpec, client) -> set[str]:
    portal, _, dataset = spec.locator.partition(":")
    body = (await client.get(f"{PORTAL_HOSTS[portal]}/api/views/{dataset}.json")).json()
    return {c["fieldName"] for c in body.get("columns", []) if isinstance(c, dict) and c.get("fieldName")}


async def scan() -> tuple[dict[str, list[str]], dict[str, list[str]]]:
    """``(generated, missing)``: the fields each Socrata module reads that the live dataset has, and the
    ones the committed file lists that the live dataset no longer has."""
    import httpx

    committed = {k: list(v) for k, v in json.loads(FIELDS_READ_PATH.read_text()).items()} if FIELDS_READ_PATH.exists() else {}
    generated: dict[str, list[str]] = {}
    missing: dict[str, list[str]] = {}
    async with httpx.AsyncClient(timeout=60, follow_redirects=True) as client:
        for spec in SOURCES:
            if spec.kind != "socrata" or spec.retired:
                continue
            try:
                cols = await _live_columns(spec, client)
            except Exception as exc:  # a dataset we can't read is a finding, not a skip
                print(f"  cannot read {spec.id}: {exc}", file=sys.stderr)
                continue
            read = fields_read(spec, cols)
            if read:
                generated[spec.id] = read
            gone = [f for f in committed.get(spec.id, []) if f not in cols]
            if gone:
                missing[spec.id] = gone
    return generated, missing


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Fields-read contracts: scan modules against live schemas.")
    ap.add_argument("--scan", action="store_true", required=True)
    ap.add_argument("--write", action="store_true", help=f"write {FIELDS_READ_PATH.name}")
    args = ap.parse_args(argv)
    generated, missing = asyncio.run(scan())
    committed = json.loads(FIELDS_READ_PATH.read_text()) if FIELDS_READ_PATH.exists() else {}
    changed = {k for k in set(generated) | set(committed) if generated.get(k) != committed.get(k)}
    print(f"{len(generated)} sources read named columns; {len(changed)} differ from {FIELDS_READ_PATH.name}")
    for k in sorted(changed):
        add = sorted(set(generated.get(k, [])) - set(committed.get(k, [])))
        drop = sorted(set(committed.get(k, [])) - set(generated.get(k, [])))
        print(f"  {k}: +{add} -{drop}")
    for k, gone in sorted(missing.items()):
        print(f"  MISSING LIVE {k}: {gone}")
    if args.write:
        FIELDS_READ_PATH.write_text(json.dumps(dict(sorted(generated.items())), indent=1) + "\n")
        print(f"wrote {FIELDS_READ_PATH}")
    return 1 if missing else 0


if __name__ == "__main__":
    sys.exit(main())
